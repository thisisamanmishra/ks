-- RLS Policies
-- ============================================================

ALTER TABLE public.staff_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.staff_appraisals ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workspace_documents ENABLE ROW LEVEL SECURITY;

-- staff_documents: own doc or admin/super_admin can see
DROP POLICY IF EXISTS "staff_documents_read" ON public.staff_documents;
CREATE POLICY "staff_documents_read" ON public.staff_documents FOR SELECT
  USING (
    user_id = (SELECT id FROM public.users WHERE email = auth.jwt()->>'email' LIMIT 1)
    OR EXISTS (
      SELECT 1 FROM public.users
      WHERE email = auth.jwt()->>'email'
        AND role IN ('super_admin', 'admin', 'board_member')
    )
  );

DROP POLICY IF EXISTS "staff_documents_insert" ON public.staff_documents;
CREATE POLICY "staff_documents_insert" ON public.staff_documents FOR INSERT
  WITH CHECK (
    EXISTS (SELECT 1 FROM public.users WHERE email = auth.jwt()->>'email')
  );

DROP POLICY IF EXISTS "staff_documents_delete" ON public.staff_documents;
CREATE POLICY "staff_documents_delete" ON public.staff_documents FOR DELETE
  USING (
    user_id = (SELECT id FROM public.users WHERE email = auth.jwt()->>'email' LIMIT 1)
    OR EXISTS (
      SELECT 1 FROM public.users
      WHERE email = auth.jwt()->>'email'
        AND role IN ('super_admin', 'admin')
    )
  );

