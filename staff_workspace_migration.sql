-- Staff Documents (joining letter, payslip, NDA, etc.)
CREATE TABLE IF NOT EXISTS public.staff_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  uploaded_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  doc_type VARCHAR(50) NOT NULL DEFAULT 'other',
  title VARCHAR(300) NOT NULL,
  doc_url TEXT,
  month VARCHAR(10),
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Staff Appraisals (linked to My Profile page)
CREATE TABLE IF NOT EXISTS public.staff_appraisals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  reviewed_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  period VARCHAR(100) NOT NULL,
  rating NUMERIC(3,1) DEFAULT 0,
  performance_score INT DEFAULT 0,
  goals_met INT DEFAULT 0,
  feedback TEXT,
  strengths TEXT,
  areas_to_improve TEXT,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Leave Requests
CREATE TABLE IF NOT EXISTS public.leave_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  leave_type VARCHAR(50) NOT NULL DEFAULT 'casual',
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  days INT NOT NULL DEFAULT 1,
  reason TEXT NOT NULL,
  status VARCHAR(20) DEFAULT 'pending',
  approved_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  approved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Workspace / Shared Team Documents
CREATE TABLE IF NOT EXISTS public.workspace_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  updated_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  title VARCHAR(300) NOT NULL,
  doc_type VARCHAR(50) DEFAULT 'document',
  content TEXT,
  doc_url TEXT,
  tags TEXT[] DEFAULT '{}',
  department VARCHAR(100),
  is_pinned BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Also ensure payroll table exists (from setup_hr_tables.sql - safe to re-run)
CREATE TABLE IF NOT EXISTS public.payroll (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  month VARCHAR(20) NOT NULL,
  year INT NOT NULL,
  base_salary DECIMAL(10,2) DEFAULT 0,
  bonuses DECIMAL(10,2) DEFAULT 0,
  deductions DECIMAL(10,2) DEFAULT 0,
  net_salary DECIMAL(10,2) DEFAULT 0,
  status VARCHAR(20) DEFAULT 'unpaid',
  payment_date TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Also ensure appraisals table exists
CREATE TABLE IF NOT EXISTS public.appraisals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  reviewer_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  review_period VARCHAR(50) NOT NULL,
  performance_score INT NOT NULL DEFAULT 0,
  feedback TEXT,
  goals_achieved TEXT,
  areas_of_improvement TEXT,
  status VARCHAR(20) DEFAULT 'draft',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

